/**
 * Sprout decorations that line the ground under the building, the footer and
 * the 404 page. The values are transcribed from the original hand-written
 * HTML, so the pattern looks exactly the same.
 */
export interface Blade {
  width: number;
  height: number;
  /** Omitted for the pink-bud sprout, which is always fully opaque. */
  opacity?: number;
  mirrored?: boolean;
  bud?: boolean;
}

const sprout = (width: number, height: number, opacity: number, mirrored = false): Blade => ({
  width,
  height,
  opacity,
  mirrored,
});
const bud = (width: number, height: number): Blade => ({ width, height, bud: true });

